from .base import BasePostProcessor, PostConfig, PostProcessError
from ..program import Motion


class KUKAKRC4PostProcessor(BasePostProcessor):
    """KUKA KRL（KRC4 / KRC5）后处理器。

    目标控制器：KUKA KRC4、KRC5
    线位移单位：毫米；角度单位：度
    """

    brand = "kuka"
    controller = "krc4"

    def __init__(self):
        super().__init__(
            PostConfig(
                precision=3,
                speed_unit="%",
                comment_char=";",
                linear_unit="mm",
                angle_unit="deg",
            )
        )

    @property
    def language_name(self) -> str:
        return "KRL"

    @property
    def file_extension(self) -> str:
        return "src"

    def _convert_motion(self, motion: Motion) -> dict:
        if self.is_joint(motion):
            return {
                "cmd": "PTP",
                "target": self.fmt_joints(motion.target),
                "speed": self.fmt_speed(motion.speed, motion.type),
                "blend": "C_DIS" if motion.blend > 0 else "",
            }
        if self.is_linear(motion):
            return {
                "cmd": "LIN",
                "target": self.fmt_pose(motion.target, order="zyx"),
                "speed": self.fmt_speed(motion.speed, motion.type),
                "blend": "C_DIS" if motion.blend > 0 else "",
            }
        if self.is_circular(motion):
            # KUKA 圆弧需要中间点（辅助点）+ 终点
            if motion.via is None:
                raise PostProcessError("KRL 圆弧运动需要提供 via 中间点")
            return {
                "cmd": "CIRC",
                "target": self.fmt_pose(motion.via, order="zyx"),
                "end": self.fmt_pose(motion.target, order="zyx"),
                "speed": self.fmt_speed(motion.speed, motion.type),
                "blend": "C_DIS" if motion.blend > 0 else "",
            }
        raise PostProcessError(f"KRL 不支持的运动类型: {motion.type}")

    def _get_template(self) -> str:
        return """&ACCESS RVP
&REL 1
DEF {{ meta.program_name|default('OROLP_PROG') }}()
    ; Generated by OpenRoboOLP v{{ meta.version|default('0.1.0') }}
    ; Robot: {{ meta.robot_name|default('unknown') }}
    BAS(#INITMOV, 0)

    {% for wp in waypoints %}
    {% if wp.cmd == 'CIRC' %}
    {{ wp.cmd }} {{ wp.target }}, {{ wp.end }} {{ wp.blend }}
    {% else %}
    {{ wp.cmd }} {{ wp.target }} {{ wp.blend }}
    {% endif %}
    {% endfor %}

    END
"""
