from typing import Dict

from .base import BasePostProcessor, PostConfig, PostProcessError
from ..program import Motion


class ABBRapidPostProcessor(BasePostProcessor):
    """ABB RAPID（IRC5 / OmniCore）后处理器。

    目标控制器：ABB IRC5、OmniCore
    线位移单位：毫米；角度单位：度
    """

    brand = "abb"
    controller = "irc5"

    def __init__(self):
        super().__init__(
            PostConfig(
                precision=3,
                speed_unit="mm/s",
                comment_char="!",
                linear_unit="mm",
                angle_unit="deg",
            )
        )

    @property
    def language_name(self) -> str:
        return "RAPID"

    @property
    def file_extension(self) -> str:
        return "mod"

    def _convert_motion(self, motion: Motion) -> dict:
        if self.is_joint(motion):
            return {
                "cmd": "MoveJ",
                "target": f"[{self.fmt_joints(motion.target)}]",
                "speed": f"v{int(round(motion.speed))}",
                "zone": f"z{int(round(motion.blend))}" if motion.blend > 0 else "fine",
            }
        if self.is_linear(motion):
            return {
                "cmd": "MoveL",
                "target": f"[{self.fmt_pose(motion.target, order='zyx')}]",
                "speed": f"v{int(round(motion.speed))}",
                "zone": f"z{int(round(motion.blend))}" if motion.blend > 0 else "fine",
            }
        if self.is_circular(motion):
            if motion.via is None:
                raise PostProcessError("RAPID 圆弧运动需要提供 via 中间点")
            return {
                "cmd": "MoveC",
                "via": f"[{self.fmt_pose(motion.via, order='zyx')}]",
                "target": f"[{self.fmt_pose(motion.target, order='zyx')}]",
                "speed": f"v{int(round(motion.speed))}",
                "zone": f"z{int(round(motion.blend))}" if motion.blend > 0 else "fine",
            }
        raise PostProcessError(f"RAPID 不支持的运动类型: {motion.type}")

    # ------------------------- IO 指令（RAPID） ------------------------- #

    def format_setdo(self, signal: str, value: bool, io_map: Dict[str, str]) -> str:
        """``SetDO <符号名>, 1;``

        RAPID 按**符号名**寻址（信号需在系统参数中声明），因此直接用逻辑名，
        物理地址以注释附在行尾便于核对。
        """
        addr = self.resolve_signal(signal, io_map)
        return f"SetDO {self.io_symbol(signal, addr)}, {'1' if value else '0'};      ! {addr}"

    def format_waitdi(
        self,
        signal: str,
        value: bool,
        timeout: float,
        io_map: Dict[str, str],
    ) -> str:
        """``WaitDI <符号名>, 1;``

        RAPID 的 ``WaitDI`` 有可选 ``\\MaxTime``，超时到点会置 ``ERRNO``；
        这里照实输出，不做静默丢弃。
        """
        addr = self.resolve_signal(signal, io_map)
        name = self.io_symbol(signal, addr)
        level = "1" if value else "0"
        if timeout and timeout > 0:
            return f"WaitDI {name}, {level} \\MaxTime:={timeout:.3f};      ! {addr}"
        return f"WaitDI {name}, {level};      ! {addr}"

    def format_waittime(self, seconds: float) -> str:
        """``WaitTime n;``"""
        return f"WaitTime {seconds:.3f};"

    def _get_template(self) -> str:
        return """MODULE {{ meta.program_name|default('OROLPModule') }}
    ! Generated by RobotWorld v{{ meta.version|default('0.1.0') }}
    ! Robot: {{ meta.robot_name|default('unknown') }}

    PROC main()
        {% for wp in waypoints %}
        {% if wp.cmd in ['SETDO', 'WAITDI', 'WAITTIME'] %}
        {{ wp.text }}
        {% elif wp.cmd == 'MoveC' %}
        {{ wp.cmd }} {{ wp.via }}, {{ wp.target }}, {{ wp.speed }}, {{ wp.zone }}, tool0;
        {% else %}
        {{ wp.cmd }} {{ wp.target }}, {{ wp.speed }}, {{ wp.zone }}, tool0;
        {% endif %}
        {% endfor %}
    ENDPROC
ENDMODULE
"""
