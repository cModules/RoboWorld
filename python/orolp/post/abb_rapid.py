from .base import BasePostProcessor, PostConfig, PostProcessError
from ..program import Motion


class ABBRapidPostProcessor(BasePostProcessor):
    """ABB RAPID（IRC5 / OmniCore）后处理器。

    目标控制器：ABB IRC5、OmniCore
    线位移单位：毫米；角度单位：度
    """

    brand = "abb"
    controller = "irc5"

    def __init__(self):
        super().__init__(
            PostConfig(
                precision=3,
                speed_unit="mm/s",
                comment_char="!",
                linear_unit="mm",
                angle_unit="deg",
            )
        )

    @property
    def language_name(self) -> str:
        return "RAPID"

    @property
    def file_extension(self) -> str:
        return "mod"

    def _convert_motion(self, motion: Motion) -> dict:
        if self.is_joint(motion):
            return {
                "cmd": "MoveJ",
                "target": f"[{self.fmt_joints(motion.target)}]",
                "speed": f"v{int(round(motion.speed))}",
                "zone": f"z{int(round(motion.blend))}" if motion.blend > 0 else "fine",
            }
        if self.is_linear(motion):
            return {
                "cmd": "MoveL",
                "target": f"[{self.fmt_pose(motion.target, order='zyx')}]",
                "speed": f"v{int(round(motion.speed))}",
                "zone": f"z{int(round(motion.blend))}" if motion.blend > 0 else "fine",
            }
        if self.is_circular(motion):
            if motion.via is None:
                raise PostProcessError("RAPID 圆弧运动需要提供 via 中间点")
            return {
                "cmd": "MoveC",
                "via": f"[{self.fmt_pose(motion.via, order='zyx')}]",
                "target": f"[{self.fmt_pose(motion.target, order='zyx')}]",
                "speed": f"v{int(round(motion.speed))}",
                "zone": f"z{int(round(motion.blend))}" if motion.blend > 0 else "fine",
            }
        raise PostProcessError(f"RAPID 不支持的运动类型: {motion.type}")

    def _get_template(self) -> str:
        return """MODULE {{ meta.program_name|default('OROLPModule') }}
    ! Generated by RobotWorld v{{ meta.version|default('0.1.0') }}
    ! Robot: {{ meta.robot_name|default('unknown') }}

    PROC main()
        {% for wp in waypoints %}
        {% if wp.cmd == 'MoveC' %}
        {{ wp.cmd }} {{ wp.via }}, {{ wp.target }}, {{ wp.speed }}, {{ wp.zone }}, tool0;
        {% else %}
        {{ wp.cmd }} {{ wp.target }}, {{ wp.speed }}, {{ wp.zone }}, tool0;
        {% endif %}
        {% endfor %}
    ENDPROC
ENDMODULE
"""
